/**
 * NEW PATIENT REGISTRATION — PRINTABLE, NEVER SUBMITTED.
 *
 * This page must stay public: the texting-platform carrier review inspects it
 * to see how SMS consent is collected.
 *
 * There is deliberately no <form> and no submit. Registration collects health
 * information — date of birth, insurance, medications — and sending that over
 * the web needs a HIPAA-eligible form service under a Business Associate
 * Agreement, which the practice does not have yet. Without a <form>, pressing
 * Enter cannot fire a GET that would put typed values into the URL, and so
 * into browser history and server logs. Patients fill it in, then print it or
 * save it as a PDF and bring it to their visit. Nothing leaves their device.
 *
 * When an online intake service is chosen, swap this for that service's
 * form, keeping the SMS consent block (wording from lib/sms.ts) and the two
 * policy links exactly as they are.
 *
 * No AOS animation on this page: AOS hides elements until they scroll into
 * view, which would leave them blank on a printout.
 */

type Span = 2 | 3 | 4 | 6

function Field({ id, label, type = 'text', autoComplete, span = 3, optional }: { id: string; label: string; type?: 'text' | 'email' | 'tel' | 'date'; autoComplete?: string; span?: Span; optional?: boolean }) {
  return (
    <p className={`field reg-span-${span}`}>
      <label htmlFor={id}>{label}{optional && <span className="reg-optional"> (optional)</span>}</label>
      <input id={id} type={type} autoComplete={autoComplete} />
    </p>
  )
}

function TextArea({ id, label, hint, rows = 3 }: { id: string; label: string; hint: string; rows?: number }) {
  return (
    <p className="field reg-span-6">
      <label htmlFor={id}>{label}</label>
      <span className="reg-hint" id={`${id}-hint`}>{hint}</span>
      <textarea id={id} rows={rows} aria-describedby={`${id}-hint`} />
    </p>
  )
}

function Choice({ name, legend, options, span = 6 }: { name: string; legend: string; options: string[]; span?: Span }) {
  return (
    <fieldset className={`reg-choice reg-span-${span}`}>
      <legend>{legend}</legend>
      <div>
        {options.map((option) => {
          const id = `${name}-${option.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`
          return <label htmlFor={id} key={option}><input id={id} type="radio" name={name} value={option} />{option}</label>
        })}
      </div>
    </fieldset>
  )
}

function Section({ id, title, children, className = '' }: { id: string; title: string; children: React.ReactNode; className?: string }) {
  return (
    <fieldset className={`reg-section ${className}`} aria-labelledby={`reg-${id}`}>
      <h2 className="reg-heading" id={`reg-${id}`}>{title}</h2>
      <div className="reg-grid">{children}</div>
    </fieldset>
  )
}

